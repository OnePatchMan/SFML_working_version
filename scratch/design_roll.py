def create_image(frames):
    img = Image.new('RGBA', (32 * len(frames), 32), (0, 0, 0, 0))
    pix = img.load()
    for f_idx, lines in enumerate(frames):
        for y in range(32):
            for x in range(32):
                ch = lines[y][x]
                pix[f_idx * 32 + x, y] = PALETTE[ch]
    return img

if __name__ == '__main__':
    for idx, f in enumerate(FRAMES):
        assert len(f) == 32, f"Frame {idx} len {len(f)}"
        for l_idx, l in enumerate(f):
            assert len(l) == 32, f"Frame {idx} line {l_idx} len {len(l)}"

    img = create_image(FRAMES)
    os.makedirs("assets/sprites", exist_ok=True)
    os.makedirs("src/sprites", exist_ok=True)
    img.save("assets/sprites/heroRoll.png")
    img.save("src/sprites/heroRoll.png")
    print(f"Generated heroRoll.png ({img.size[0]}x{img.size[1]}) in assets/sprites/ and src/sprites/")
