def create_sheet(frames):
    img = Image.new('RGBA', (32 * len(frames), 32), (0, 0, 0, 0))
    pix = img.load()
    for f_idx, lines in enumerate(frames):
        assert len(lines) == 32, f"Frame {f_idx} has {len(lines)} lines"
        for y in range(32):
            line = lines[y]
            assert len(line) == 32, f"Frame {f_idx} line {y} has length {len(line)} != 32"
            for x in range(32):
                ch = line[x]
                pix[f_idx * 32 + x, y] = PALETTE.get(ch, (0, 0, 0, 0))
    return img

